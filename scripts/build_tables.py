def _t3_row(condition, ing, cls, t7):
    if ing in t7 and cls.startswith("strong anticholinergic"):
        return f"{condition} > Anticholinergics (see Table 7: {T7_CATEGORY[ing]})"
    names = {"antipsychotic": "Antipsychotics", "benzodiazepine": "Benzodiazepines", "z-drug": "Z-drugs",
             "antiepileptic": "Antiepileptics", "antidepressant (TCA/SSRI/SNRI)": "Antidepressants (TCAs, SSRIs, SNRIs)",
             "opioid": "Opioids"}
    return f"{condition} > {names[cls]} (class membership per WHO ATC)"


def _split(s):
    multi = ["ergoloid mesylates", "conjugated estrogens", "esterified estrogens", "mineral oil", "valproic acid", "ethacrynic acid"]
    out, rest = [], " " + s + " "
    for m in multi:
        if f" {m} " in rest:
            out.append(m)
            rest = rest.replace(f" {m} ", " ")
    return out + rest.split()


